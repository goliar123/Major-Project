"""
Test script to verify that local Ollama (llama3.2) is connected and producing output.
"""
import sys
import time
from pathlib import Path

# Add project root to sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from core.llm_client import llm_client
from core.step_judge import step_judge
from dataset.schema import ExecutionStep
from config.settings import settings
from rich.console import Console
from rich.panel import Panel

console = Console()

def test_connection():
    console.print(Panel(
        f"[bold cyan]🔍 Testing Ollama Connection[/bold cyan]\n"
        f"[bold]Provider:[/bold] {settings.LLM_PROVIDER}\n"
        f"[bold]Model:[/bold] {settings.LLM_MODEL}\n"
        f"[bold]Base URL:[/bold] {settings.LLM_BASE_URL}",
        title="Ollama Diagnostic Test",
        border_style="cyan"
    ))

    # Test step: A flawed database drop
    sample_step = ExecutionStep(
        step_index=1,
        agent_name="DBArchitect",
        action_type="sql_migration",
        action_payload="DROP TABLE users; -- Deleting old table to create new schema",
        output_state="Table dropped."
    )

    task_goal = "Migrate database schema while preserving all user records."

    console.print("[bold yellow]Sending step to llama3.2 for evaluation...[/bold yellow]")
    start = time.time()
    
    try:
        evaluation = step_judge.evaluate_step(task_goal, sample_step)
        elapsed = time.time() - start

        console.print(Panel(
            f"[bold green]✅ Model Output Received Successfully in {elapsed:.2f}s![/bold green]\n\n"
            f"• [bold]Is Valid Step:[/bold] {evaluation.is_valid}\n"
            f"• [bold]Health Score:[/bold] {evaluation.score:.2f} / 1.00\n"
            f"• [bold]Anomaly Detected:[/bold] {evaluation.anomaly_detected}\n"
            f"• [bold]Error Category:[/bold] {evaluation.error_category}\n"
            f"• [bold]Judge Justification (Generated by llama3.2):[/bold]\n  [white]{evaluation.justification}[/white]\n"
            f"• [bold]Cached in SQLite:[/bold] {evaluation.cached}",
            title="[bold green]Llama-3.2 Evaluation Result[/bold green]",
            border_style="green"
        ))
    except Exception as e:
        console.print(Panel(
            f"[bold red]❌ Connection Error:[/bold red] {e}\n\n"
            f"[yellow]Make sure Ollama is running (`ollama run llama3.2:latest`) and listening on port 11434.[/yellow]",
            title="Connection Failed",
            border_style="red"
        ))

if __name__ == "__main__":
    test_connection()
